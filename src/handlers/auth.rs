#[derive(Template)]
#[template(path = "register.html")]
struct RegisterTemplate {
    title: String,
    layout: Layout,
    errors: Vec<FormError>,
    // Values kept when the form is shown again after an error, never the password.
    username: String,
    email: String,
    firstname: String,
    lastname: String,
    birthday: String,
    // Limits used by the form inputs, the minimum age is checked by the server.
    today: String,
    username_max_len: usize,
    email_max_len: usize,
    name_max_chars: usize,
    password_min_chars: usize,
    password_max_chars: usize,
}

impl RegisterTemplate {
    fn new(layout: Layout, form: &HashMap<String, String>) -> Self {
        Self {
            title: "Register".to_string(),
            layout,
            errors: Vec::new(),
            username: field(form, "username").trim().to_string(),
            email: field(form, "email").trim().to_string(),
            firstname: field(form, "firstname").trim().to_string(),
            lastname: field(form, "lastname").trim().to_string(),
            birthday: field(form, "birthday").trim().to_string(),
            today: Utc::now().date_naive().format("%Y-%m-%d").to_string(),
            username_max_len: USERNAME_MAX_LEN,
            email_max_len: EMAIL_MAX_LEN,
            name_max_chars: NAME_MAX_CHARS,
            password_min_chars: PASSWORD_MIN_CHARS,
            password_max_chars: PASSWORD_MAX_CHARS,
        }
    }

    fn with_errors(mut self, status: StatusCode, errors: Vec<FormError>) -> Response {
        self.errors = errors;
        (status, render_template(&self)).into_response()
    }

    fn error_for(&self, field: &str) -> Option<&str> {
        error_for(&self.errors, field)
    }

    fn general_errors(&self) -> Vec<&str> {
        general_errors(&self.errors)
    }
}

/// First or last name: required, and valid.
fn required_name(
    form: &HashMap<String, String>,
    key: &'static str,
    label: &str,
    errors: &mut Vec<FormError>,
) -> Option<String> {
    match user::validate_name(field(form, key)) {
        Some(name) if !name.is_empty() => Some(name),
        Some(_) => {
            errors.push(FormError::field(key, format!("Enter your {label}.")));
            None
        }
        None => {
            errors.push(FormError::field(
                key,
                format!("At most {NAME_MAX_CHARS} characters, without control characters."),
            ));
            None
        }
    }
}

pub async fn register_page(State(state): State<AppState>, session: Session) -> Response {
    let layout = Layout::load(&state, &session).await;
    if let Some(redirect) = redirect_signed_in(&layout) {
        return redirect;
    }
    render_template(&RegisterTemplate::new(layout, &HashMap::new()))
}

/// Checks every field and returns the account to create with its password,
/// or every problem found so they can all be fixed at once.
fn validate_registration(
    form: &HashMap<String, String>,
    today: NaiveDate,
) -> Result<(NewAccount, String), Vec<FormError>> {
    let mut errors = Vec::new();

    let username = user::validate_username(field(form, "username"));
    if username.is_none() {
        errors.push(FormError::field(
            "username",
            format!("{USERNAME_MIN_LEN} to {USERNAME_MAX_LEN} characters, using only letters, digits and _."),
        ));
    }

    let email = user::validate_email(field(form, "email"));
    if email.is_none() {
        errors.push(FormError::field("email", "Enter a valid email address."));
    }

    let firstname = required_name(form, "firstname", "first name", &mut errors);
    let lastname = required_name(form, "lastname", "last name", &mut errors);

    let birthday = user::validate_birthday(field(form, "birthday"), today);
    if birthday.is_none() {
        let message = if field(form, "birthday").trim().is_empty() {
            "Enter your birthday.".to_string()
        } else {
            format!("You must be at least {MIN_AGE_YEARS} years old to register.")
        };
        errors.push(FormError::field("birthday", message));
    }

    let password = field(form, "password");
    if !user::validate_password(password) {
        errors.push(FormError::field(
            "password",
            format!(
                "{PASSWORD_MIN_CHARS} to {PASSWORD_MAX_CHARS} characters, with an uppercase letter, a lowercase letter, a digit and a symbol. Spaces are allowed only one at a time, between words."
            ),
        ));
    } else if password != field(form, "password_confirm") {
        errors.push(FormError::field("password_confirm", "The two passwords are different."));
    }

    match (username, email, firstname, lastname, birthday) {
        (Some(username), Some(email), Some(firstname), Some(lastname), Some(birthday))
            if errors.is_empty() =>
        {
            let account = NewAccount {
                username,
                email,
                password_hash: String::new(),
                firstname,
                lastname,
                birthday,
            };
            Ok((account, password.to_string()))
        }
        _ => Err(errors),
    }
}

pub async fn register(
    State(state): State<AppState>,
    session: Session,
    Form(form): Form<HashMap<String, String>>,
) -> Response {
    let layout = Layout::load(&state, &session).await;
    if let Some(redirect) = redirect_signed_in(&layout) {
        return redirect;
    }
    let Some(pool) = &state.pool else {
        return error_page(layout, StatusCode::SERVICE_UNAVAILABLE, "The database is not configured.");
    };
    let page = RegisterTemplate::new(layout, &form);

    let (mut account, password) = match validate_registration(&form, Utc::now().date_naive()) {
        Ok(valid) => valid,
        Err(errors) => return page.with_errors(StatusCode::BAD_REQUEST, errors),
    };
    let Some(password_hash) = hash_password_blocking(password).await else {
        return page.with_errors(StatusCode::INTERNAL_SERVER_ERROR, vec![server_error()]);
    };
    account.password_hash = password_hash;

    let created = match user::create_account(pool, &account).await {
        Ok(created) => created,
        Err(CreateAccountError::UsernameTaken) => {
            let error = FormError::field("username", "This username is already taken.");
            return page.with_errors(StatusCode::CONFLICT, vec![error]);
        }
        Err(CreateAccountError::EmailTaken) => {
            let error = FormError::field("email", "An account already uses this email.");
            return page.with_errors(StatusCode::CONFLICT, vec![error]);
        }
        Err(CreateAccountError::Database(err)) => {
            tracing::error!("account creation failed: {}", err);
            return page.with_errors(StatusCode::INTERNAL_SERVER_ERROR, vec![server_error()]);
        }
    };

    if let Err(err) = sign_in(&session, &created).await {
        tracing::error!("failed to sign in new user {}: {}", created.id, err);
        return Redirect::to("/login").into_response();
    }
    tracing::info!("new account @{}", created.username);
    // A new account stays signed in, like the login form's default.
    signed_in_redirect(&state, created.id, true, &format!("/user/{}", created.username)).await
}

/// Redirect after signing in, with the "stay signed in" cookie when asked.
async fn signed_in_redirect(state: &AppState, user_id: i32, stay_signed_in: bool, to: &str) -> Response {
    let mut response = Redirect::to(to).into_response();
    if stay_signed_in && let Some(cookie) = remember(state, user_id).await {
        response.headers_mut().append(SET_COOKIE, cookie);
    }
    response
}

