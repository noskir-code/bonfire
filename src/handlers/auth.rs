/// The random salt is generated by argon2 from the operating system.
fn hash_password(password: &str) -> Result<String, argon2::password_hash::Error> {
    Ok(Argon2::default().hash_password(password.as_bytes())?.to_string())
}

/// `hash` is the PHC string stored in the database (`$argon2id$v=19$...`).
fn verify_password(password: &str, hash: &str) -> bool {
    Argon2::default()
        .verify_password(password.as_bytes(), hash)
        .is_ok()
}

/// Checked when the account does not exist, so the answer takes as long as
/// for a wrong password and does not reveal which usernames exist.
fn dummy_hash() -> &'static str {
    static DUMMY_HASH: OnceLock<String> = OnceLock::new();
    DUMMY_HASH.get_or_init(|| hash_password("dummy password").unwrap_or_default())
}

/// Argon2 is slow on purpose: run it outside the async threads.
/// Also used for the "stay signed in" tokens.
pub(crate) async fn hash_password_blocking(password: String) -> Option<String> {
    tokio::task::spawn_blocking(move || hash_password(&password))
        .await
        .ok()?
        .map_err(|err| tracing::error!("password hashing failed: {}", err))
        .ok()
}

pub(crate) async fn verify_password_blocking(password: String, hash: Option<String>) -> bool {
    tokio::task::spawn_blocking(move || match hash {
        Some(hash) => verify_password(&password, &hash),
        None => {
            verify_password(&password, dummy_hash());
            false
        }
    })
    .await
    .unwrap_or(false)
}

fn field<'a>(form: &'a HashMap<String, String>, key: &str) -> &'a str {
    form.get(key).map(String::as_str).unwrap_or("")
}

/// Already signed-in users are sent to their profile instead of the login/register forms.
fn redirect_signed_in(layout: &Layout) -> Option<Response> {
    layout
        .viewer
        .as_ref()
        .map(|viewer| Redirect::to(&format!("/user/{}", viewer.username)).into_response())
}

/// A problem shown on the form: the field gets a red border and the message
/// is shown under it. `field` is `None` for problems not caused by a field.
pub(crate) struct FormError {
    field: Option<&'static str>,
    message: String,
}

impl FormError {
    pub(crate) fn field(field: &'static str, message: impl Into<String>) -> Self {
        Self {
            field: Some(field),
            message: message.into(),
        }
    }

    pub(crate) fn general(message: impl Into<String>) -> Self {
        Self {
            field: None,
            message: message.into(),
        }
    }
}

pub(crate) fn server_error() -> FormError {
    FormError::general("Something went wrong, try again later.")
}

/// Message for `field`, used by the templates to mark it.
pub(crate) fn error_for<'a>(errors: &'a [FormError], field: &str) -> Option<&'a str> {
    errors
        .iter()
        .find(|error| error.field == Some(field))
        .map(|error| error.message.as_str())
}

pub(crate) fn general_errors(errors: &[FormError]) -> Vec<&str> {
    errors
        .iter()
        .filter(|error| error.field.is_none())
        .map(|error| error.message.as_str())
        .collect()
}

