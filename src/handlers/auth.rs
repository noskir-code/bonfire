#[derive(Template)]
#[template(path = "login.html")]
struct LoginTemplate {
    title: String,
    layout: Layout,
    errors: Vec<FormError>,
    /// Username or email, kept when the form is shown again.
    login: String,
    /// Coming from "forgot password": the password was just changed.
    password_reset: bool,
}

impl LoginTemplate {
    fn error_for(&self, field: &str) -> Option<&str> {
        error_for(&self.errors, field)
    }

    fn general_errors(&self) -> Vec<&str> {
        general_errors(&self.errors)
    }
}

pub async fn login_page(
    State(state): State<AppState>,
    session: Session,
    Query(query): Query<HashMap<String, String>>,
) -> Response {
    let layout = Layout::load(&state, &session).await;
    if let Some(redirect) = redirect_signed_in(&layout) {
        return redirect;
    }
    render_template(&LoginTemplate {
        title: "Login".to_string(),
        layout,
        errors: Vec::new(),
        login: String::new(),
        password_reset: query.contains_key("reset"),
    })
}

pub async fn login(
    State(state): State<AppState>,
    session: Session,
    Form(form): Form<HashMap<String, String>>,
) -> Response {
    let layout = Layout::load(&state, &session).await;
    if let Some(redirect) = redirect_signed_in(&layout) {
        return redirect;
    }
    let Some(pool) = &state.pool else {
        return error_page(layout, StatusCode::SERVICE_UNAVAILABLE, "The database is not configured.");
    };

    let login = field(&form, "login").trim().to_string();
    let password = field(&form, "password").to_string();
    let show_errors = |layout, status, errors| {
        let template = LoginTemplate {
            title: "Login".to_string(),
            layout,
            errors,
            login: login.clone(),
            password_reset: false,
        };
        (status, render_template(&template)).into_response()
    };

    let mut missing = Vec::new();
    if login.is_empty() {
        missing.push(FormError::field("login", "Enter your username or email."));
    }
    if password.is_empty() {
        missing.push(FormError::field("password", "Enter your password."));
    }
    if !missing.is_empty() {
        return show_errors(layout, StatusCode::BAD_REQUEST, missing);
    }

    let (user_id, hash) = match user::find_credentials(pool, &login).await {
        Ok(Some((user_id, hash))) => (Some(user_id), hash),
        Ok(None) => (None, None),
        Err(err) => {
            tracing::error!("failed to load credentials: {}", err);
            return show_errors(layout, StatusCode::INTERNAL_SERVER_ERROR, vec![server_error()]);
        }
    };

    // Always verified, against the dummy hash when there is no account,
    // and the same message whether the account exists or not:
    // both fields are marked since telling which one is wrong would reveal it.
    let verified = verify_password_blocking(password, hash).await;
    let Some(user_id) = user_id.filter(|_| verified) else {
        let errors = vec![
            FormError::field("login", ""),
            FormError::field("password", "Wrong username, email or password."),
        ];
        return show_errors(layout, StatusCode::UNAUTHORIZED, errors);
    };

    let signed_in_user = match user::find_by_id(pool, user_id).await {
        Ok(Some(found)) => found,
        Ok(None) => return show_errors(layout, StatusCode::INTERNAL_SERVER_ERROR, vec![server_error()]),
        Err(err) => {
            tracing::error!("failed to load user {}: {}", user_id, err);
            return show_errors(layout, StatusCode::INTERNAL_SERVER_ERROR, vec![server_error()]);
        }
    };
    if let Err(err) = sign_in(&session, &signed_in_user).await {
        tracing::error!("failed to sign in user {}: {}", user_id, err);
        return show_errors(layout, StatusCode::INTERNAL_SERVER_ERROR, vec![server_error()]);
    }
    // A checkbox is only sent when checked.
    let stay_signed_in = form.contains_key("remember");
    signed_in_redirect(&state, user_id, stay_signed_in, "/").await
}

pub async fn logout(State(state): State<AppState>, session: Session, headers: HeaderMap) -> Response {
    forget(&state, &headers).await;
    if let Err(err) = sign_out(&session).await {
        tracing::error!("failed to sign out: {}", err);
    }
    let mut response = Redirect::to("/").into_response();
    if let Some(cookie) = forget_cookie(state.secure_cookies) {
        response.headers_mut().append(SET_COOKIE, cookie);
    }
    response
}
